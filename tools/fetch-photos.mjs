// Downloads one freely licensed photo per place from Wikimedia Commons and writes
// photos/<id>.jpg, photos/CREDITS.md and photos.js (credit data used by the page).
//
// Usage: node tools/fetch-photos.mjs
// Each place uses the lead image of an English Wikipedia article, unless `file` is given.
import { mkdirSync, writeFileSync } from 'node:fs';

const PLACES = [
  { id: 'tokyo', title: 'Tokyo' },
  { id: 'nagoya', title: 'Nagoya Castle' },
  { id: 'osaka', title: 'Osaka Castle' },
  { id: 'okayama', title: 'Okayama Castle' },
  { id: 'hiroshima', title: 'Itsukushima Shrine' },
  { id: 'fukuoka', title: 'Fukuoka Tower' },
  { id: 'kumamoto', title: 'Kumamoto Castle' },
  { id: 'kagoshima', title: 'Sakurajima' },
  // the article's lead image is under a Korean open-government license, so pick a CC photo instead
  {
    id: 'seoul',
    title: 'Gyeongbokgung',
    file: 'File:Front view of the Imperial Throne Hall Geunjeongjeon at Gyeongbokgung Palace with blue sky in Seoul.jpg',
  },
  { id: 'shanghai', title: 'The Bund' },
  // the article's lead image is an old map, so pick a skyline photo instead
  { id: 'hongkong', title: 'Victoria Harbour', file: 'File:Victoria Harbour skyscrapers.jpg' },
  { id: 'bangkok', title: 'Wat Arun' },
  { id: 'singapore', title: 'Merlion' },
  { id: 'dubai', title: 'Burj Khalifa' },
  { id: 'paris', title: 'Eiffel Tower' },
];

const OVERRIDES = JSON.parse(process.env.PHOTO_OVERRIDES || '{}'); // { id: "File:Name.jpg" }
const WIDTH = 800;
const UA = 'TravelTimerStudentProject/1.0 (https://github.com/nagi321/hello-site; personal study project)';
const FREE = /^(CC BY|CC0|Public domain|PD|Attribution)/i;

// network errors are sometimes transient, so try a few times
async function fetchRetry(url) {
  let lastError;
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': UA } });
      if (res.ok) return res;
      lastError = new Error(`HTTP ${res.status} ${url}`);
    } catch (error) {
      lastError = error;
    }
    await new Promise((resolve) => setTimeout(resolve, 1500 * attempt));
  }
  throw lastError;
}

async function api(host, params) {
  const url = `https://${host}/w/api.php?${new URLSearchParams({ format: 'json', formatversion: '2', ...params })}`;
  return (await fetchRetry(url)).json();
}

function plain(html) {
  return String(html || '')
    .replace(/<[^>]*>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim();
}

async function leadFile(title) {
  const data = await api('en.wikipedia.org', { action: 'query', prop: 'pageimages', piprop: 'name', titles: title, redirects: '1' });
  const name = data.query.pages[0].pageimage;
  if (!name) throw new Error(`no lead image for ${title}`);
  return `File:${name}`;
}

mkdirSync('photos', { recursive: true });
const credits = {};
const lines = ['# Photo credits', '', 'Photos come from Wikimedia Commons. They were resized to 800 px wide.', ''];

for (const place of PLACES) {
  try {
    const file = place.file || OVERRIDES[place.id] || await leadFile(place.title);
    const data = await api('commons.wikimedia.org', {
      action: 'query', prop: 'imageinfo', titles: file, iiprop: 'url|extmetadata|size|mime', iiurlwidth: String(WIDTH),
    });
    const info = data.query.pages[0].imageinfo[0];
    const meta = info.extmetadata;
    const license = plain(meta.LicenseShortName && meta.LicenseShortName.value);
    const author = plain(meta.Artist && meta.Artist.value).slice(0, 80) || 'Unknown';
    if (!FREE.test(license)) {
      console.log(`SKIP ${place.id}: license "${license}" (${file})`);
      continue;
    }
    const res = await fetchRetry(info.thumburl);
    const bytes = Buffer.from(await res.arrayBuffer());
    writeFileSync(`photos/${place.id}.jpg`, bytes);

    credits[place.id] = {
      file: `photos/${place.id}.jpg`,
      author,
      license,
      licenseUrl: plain(meta.LicenseUrl && meta.LicenseUrl.value),
      page: info.descriptionurl,
    };
    lines.push(`- ${place.id}: ${author} / ${license} / ${info.descriptionurl}`);
    console.log(`OK   ${place.id}: ${file} | ${license} | ${author} | ${Math.round(bytes.length / 1024)} KB`);
  } catch (error) {
    console.log(`FAIL ${place.id}: ${error.message}`);
  }
  await new Promise((resolve) => setTimeout(resolve, 400)); // be gentle with the API
}

writeFileSync('photos/CREDITS.md', `${lines.join('\n')}\n`);
writeFileSync('photos.js', `// Generated by tools/fetch-photos.mjs. Photos: Wikimedia Commons (see photos/CREDITS.md).\nwindow.PHOTOS = ${JSON.stringify(credits, null, 1)};\n`);
